-- K-Loud shared cloud data model.
-- Run this entire file once in Supabase SQL Editor.
-- It migrates existing people/events data without re-seeding on refresh.

create extension if not exists pgcrypto;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  groups text[] not null default '{}',
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  legacy_id text,
  name text not null,
  role text not null default '',
  group_name text not null default '未分组',
  color text not null default '#4778f5',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (team_id, legacy_id)
);

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  legacy_event_id text,
  title text not null,
  city text not null default '',
  business_type text not null default '未分类',
  venue text not null default '',
  notes text not null default '',
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (team_id, legacy_event_id)
);

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  project_id uuid not null references public.projects(id) on delete cascade,
  member_id uuid not null references public.members(id) on delete restrict,
  start_at timestamp without time zone not null,
  end_at timestamp without time zone not null,
  status text not null check (status in ('confirmed', 'pending', 'progress', 'draft')),
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint assignments_time_order check (end_at > start_at)
);

create table if not exists public.event_audit_logs (
  id bigint generated by default as identity primary key,
  event_id text not null,
  event_title text not null default '',
  action text not null check (action in ('insert', 'update', 'delete')),
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text not null default '系统',
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

create index if not exists members_team_id_idx on public.members(team_id);
create index if not exists projects_team_id_idx on public.projects(team_id);
create index if not exists assignments_team_id_idx on public.assignments(team_id);
create index if not exists assignments_member_time_idx on public.assignments(member_id, start_at, end_at);

alter table public.profiles add column if not exists team_id uuid references public.teams(id) on delete set null;
alter table public.profiles add column if not exists member_id uuid references public.members(id) on delete set null;
alter table public.event_audit_logs add column if not exists team_id uuid references public.teams(id) on delete cascade;

do $$
declare
  default_team_id uuid;
begin
  select id into default_team_id from public.teams order by created_at limit 1;

  if default_team_id is null then
    insert into public.teams (name, groups)
    values ('K-Loud', array['业务一组','业务二组','演出组','内容组','商务组'])
    returning id into default_team_id;
  end if;

  update public.profiles set team_id = default_team_id where team_id is null;
  update public.event_audit_logs set team_id = default_team_id where team_id is null;

  if to_regclass('public.people') is not null then
    insert into public.members (team_id, legacy_id, name, role, group_name, color)
    select default_team_id, p.id, p.name, p.role, p.group_name, p.color
    from public.people p
    on conflict (team_id, legacy_id) do update
      set name = excluded.name,
          role = excluded.role,
          group_name = excluded.group_name,
          color = excluded.color,
          updated_at = now();
  end if;

  if to_regclass('public.events') is not null then
    insert into public.projects (
      team_id, legacy_event_id, title, city, business_type, venue, notes, created_by
    )
    select
      default_team_id, e.id, e.title, e.city, e.business_type, e.venue, e.notes, e.created_by
    from public.events e
    on conflict (team_id, legacy_event_id) do update
      set title = excluded.title,
          city = excluded.city,
          business_type = excluded.business_type,
          venue = excluded.venue,
          notes = excluded.notes,
          updated_at = now();

    insert into public.assignments (
      team_id, project_id, member_id, start_at, end_at, status, created_by
    )
    select
      default_team_id,
      pr.id,
      m.id,
      e.start_at,
      e.end_at,
      e.status,
      e.created_by
    from public.events e
    join public.projects pr
      on pr.team_id = default_team_id and pr.legacy_event_id = e.id
    join public.members m
      on m.team_id = default_team_id and m.legacy_id = e.owner_id
    where not exists (
      select 1 from public.assignments a where a.project_id = pr.id
    );
  end if;

  update public.profiles p
     set member_id = m.id
    from public.members m
   where p.team_id = m.team_id
     and p.person_id = m.legacy_id
     and p.member_id is null;
end
$$;

create or replace function public.current_team_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select team_id from public.profiles where id = auth.uid();
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  default_team_id uuid;
begin
  select id into default_team_id from public.teams order by created_at limit 1;
  insert into public.profiles (id, full_name, team_id)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1), ''),
    default_team_id
  )
  on conflict (id) do update
    set team_id = coalesce(public.profiles.team_id, excluded.team_id);
  return new;
end;
$$;

