create or replace function public.audit_assignment_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_label text;
  project_title text;
  target_assignment_id uuid;
  target_project_id uuid;
begin
  target_assignment_id := case when tg_op = 'DELETE' then old.id else new.id end;
  target_project_id := case when tg_op = 'DELETE' then old.project_id else new.project_id end;
  select title into project_title from public.projects where id = target_project_id;
  select coalesce(nullif(p.full_name,''), split_part(u.email,'@',1), '系统')
    into actor_label
    from auth.users u left join public.profiles p on p.id = u.id
   where u.id = auth.uid();

  insert into public.event_audit_logs (
    team_id, event_id, event_title, action, actor_id, actor_name, old_data, new_data
  ) values (
    case when tg_op = 'DELETE' then old.team_id else new.team_id end,
    target_assignment_id::text,
    coalesce(project_title, '未命名项目'),
    lower(tg_op),
    auth.uid(),
    coalesce(actor_label,'系统'),
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end
  );
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

