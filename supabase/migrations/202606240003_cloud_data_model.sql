grant execute on function public.delete_schedule(uuid) to authenticated;

drop function if exists public.admin_list_accounts();
create or replace function public.admin_list_accounts()
returns table (
  user_id uuid,
  email text,
  full_name text,
  role public.app_role,
  member_id uuid,
  member_name text,
  last_sign_in_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.current_app_role() <> 'admin' then
    raise exception 'Only administrators can manage accounts';
  end if;
  return query
  select u.id, u.email::text, p.full_name, p.role, p.member_id, m.name, u.last_sign_in_at
  from auth.users u
  join public.profiles p on p.id = u.id
  left join public.members m on m.id = p.member_id
  where p.team_id = public.current_team_id()
  order by u.email;
end;
$$;

drop function if exists public.admin_update_account(uuid, text, public.app_role);
drop function if exists public.admin_update_account(uuid, uuid, public.app_role);
create or replace function public.admin_update_account(
  target_user_id uuid,
  target_member_id uuid,
  target_role public.app_role
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  linked_name text;
begin
  if public.current_app_role() <> 'admin' then
    raise exception 'Only administrators can manage accounts';
  end if;
  if target_member_id is not null then
    select name into linked_name
    from public.members
    where id = target_member_id and team_id = public.current_team_id();
    if linked_name is null then raise exception 'Selected member does not belong to this team'; end if;
  end if;

  update public.profiles
     set member_id = target_member_id,
         person_id = null,
         role = target_role,
         full_name = coalesce(linked_name, nullif(full_name,''), '团队成员'),
         updated_at = now()
   where id = target_user_id and team_id = public.current_team_id();
  if not found then raise exception 'Account does not belong to this team'; end if;
end;
$$;

grant execute on function public.admin_list_accounts() to authenticated;
