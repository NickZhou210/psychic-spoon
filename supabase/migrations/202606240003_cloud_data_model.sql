create or replace function public.save_schedule(
  p_assignment_id uuid,
  p_project_id uuid,
  p_member_id uuid,
  p_title text,
  p_start_at timestamp without time zone,
  p_end_at timestamp without time zone,
  p_status text,
  p_city text,
  p_business_type text,
  p_venue text,
  p_notes text
)
returns table (assignment_id uuid, project_id uuid)
language plpgsql
security invoker
set search_path = public
as $$
declare
  active_team uuid := public.current_team_id();
  saved_project_id uuid;
  saved_assignment_id uuid;
begin
  if public.current_app_role() not in ('admin','editor') then
    raise exception 'Current account is read-only';
  end if;
  if active_team is null then raise exception 'Account is not assigned to a team'; end if;
  if not exists (select 1 from public.members where id = p_member_id and team_id = active_team) then
    raise exception 'Selected member does not belong to this team';
  end if;

  if p_project_id is null then
    insert into public.projects (team_id, title, city, business_type, venue, notes)
    values (active_team, p_title, coalesce(p_city,''), coalesce(p_business_type,'未分类'), coalesce(p_venue,''), coalesce(p_notes,''))
    returning id into saved_project_id;
  else
    update public.projects
       set title = p_title,
           city = coalesce(p_city,''),
           business_type = coalesce(p_business_type,'未分类'),
           venue = coalesce(p_venue,''),
           notes = coalesce(p_notes,'')
     where id = p_project_id and team_id = active_team
     returning id into saved_project_id;
    if saved_project_id is null then raise exception 'Project does not exist'; end if;
  end if;

  if p_assignment_id is null then
    insert into public.assignments (team_id, project_id, member_id, start_at, end_at, status)
    values (active_team, saved_project_id, p_member_id, p_start_at, p_end_at, p_status)
    returning id into saved_assignment_id;
  else
    update public.assignments
       set member_id = p_member_id,
           start_at = p_start_at,
           end_at = p_end_at,
           status = p_status
     where id = p_assignment_id and team_id = active_team
     returning id into saved_assignment_id;
    if saved_assignment_id is null then raise exception 'Assignment does not exist'; end if;
  end if;

  return query select saved_assignment_id, saved_project_id;
end;
$$;

create or replace function public.delete_schedule(p_assignment_id uuid)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  active_team uuid := public.current_team_id();
  linked_project uuid;
begin
  if public.current_app_role() not in ('admin','editor') then
    raise exception 'Current account is read-only';
  end if;

  delete from public.assignments
   where id = p_assignment_id and team_id = active_team
  returning project_id into linked_project;

  if linked_project is null then raise exception 'Assignment does not exist'; end if;
  if not exists (select 1 from public.assignments where project_id = linked_project) then
    delete from public.projects where id = linked_project and team_id = active_team;
  end if;
end;
$$;

