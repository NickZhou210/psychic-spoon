returns table (
  audit_trigger_enabled boolean,
  assignments_realtime_enabled boolean,
  projects_realtime_enabled boolean,
  members_realtime_enabled boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select
    exists (select 1 from pg_trigger where tgname = 'assignments_audit_change' and not tgisinternal),
    exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='assignments'),
    exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='projects'),
    exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='members');
$$;

