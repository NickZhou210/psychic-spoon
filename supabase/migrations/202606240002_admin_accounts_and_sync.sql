create or replace function public.get_schedule_system_status()
returns table (
  audit_trigger_enabled boolean,
  events_realtime_enabled boolean,
  audit_realtime_enabled boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select
    exists (
      select 1 from pg_trigger
      where tgname = 'events_audit_change' and not tgisinternal
    ),
    exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'events'
    ),
    exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'event_audit_logs'
    );
$$;

grant execute on function public.get_schedule_system_status() to authenticated;

